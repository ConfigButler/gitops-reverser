#!/usr/bin/env bash
set -euo pipefail

# Deploy the mutation-capture lab and the wardle sample aggregated API server onto the lab's own
# cluster, and wait until both serve. Idempotent: an unchanged image and certificate set applies
# as a no-op.
#
# Inputs (env):
# - LAB_CLUSTER_NAME (required): k3d cluster name, without the k3d- prefix
# - LAB_CTX (required): its kube context
# - LAB_CS (required): its stamp directory, holding certs/ from test/mutationlab/tools/lab-certs
# - LAB_IMAGE (required): the lab image, already built
# - LAB_NAMESPACE (optional, default mutation-capture-lab)
# - K3D / KUBECTL / CONTAINER_TOOL (optional): tool overrides

: "${LAB_CLUSTER_NAME:?LAB_CLUSTER_NAME is required}"
: "${LAB_CTX:?LAB_CTX is required}"
: "${LAB_CS:?LAB_CS is required}"
: "${LAB_IMAGE:?LAB_IMAGE is required}"
LAB_NAMESPACE="${LAB_NAMESPACE:-mutation-capture-lab}"
K3D="${K3D:-k3d}"
KUBECTL="${KUBECTL:-kubectl}"
CONTAINER_TOOL="${CONTAINER_TOOL:-docker}"
NODE="k3d-${LAB_CLUSTER_NAME}-server-0"
LAB_DIR="test/mutationlab"
SAMPLE_APISERVER_DIR="test/e2e/setup/manifests/sample-apiserver"

kubectl_lab() { "${KUBECTL}" --context "${LAB_CTX}" "$@"; }

image_in_node() { "${CONTAINER_TOOL}" exec "${NODE}" crictl inspecti "${LAB_IMAGE}" >/dev/null 2>&1; }

# import_image delivers the lab image into the node. `-m direct` streams `docker save` straight
# into the node's `ctr image import`: the default tools-node mode can misread the save as finished
# before the tarball lands and still exit 0. Direct mode can hang instead, so each attempt is
# bounded, and every attempt is checked against the node rather than trusted.
import_image() {
    if image_in_node; then
        echo "✅ ${LAB_IMAGE} is already in ${NODE}"
        return 0
    fi
    local attempt
    for attempt in 1 2 3; do
        echo "📦 Importing ${LAB_IMAGE} into ${LAB_CLUSTER_NAME} (attempt ${attempt}/3)…"
        timeout --kill-after=10s 300s "${K3D}" image import -m direct -c "${LAB_CLUSTER_NAME}" "${LAB_IMAGE}" || true
        if image_in_node; then
            return 0
        fi
    done
    echo "❌ ${LAB_IMAGE} did not reach ${NODE} after 3 attempts" >&2
    return 1
}

# write_overlay renders the overlay that binds the tracked manifests to this cluster: the image
# tag, the Secret with the issued certificates, and the CA as the registration's caBundle. It
# lives in the stamp directory beside certs/, because kustomize reads a generator's files only
# from inside its own root.
write_overlay() {
    local base ca_bundle
    base="$(realpath --relative-to="${LAB_CS}" "${LAB_DIR}/deploy")"
    ca_bundle="$(base64 -w0 <"${LAB_CS}/certs/ca.crt")"
    cat >"${LAB_CS}/kustomization.yaml" <<EOF
# Generated by test/mutationlab/deploy.sh; do not edit.
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
  - ${base}
images:
  - name: mutation-capture-lab
    newName: ${LAB_IMAGE%:*}
    newTag: ${LAB_IMAGE##*:}
secretGenerator:
  - name: mutation-capture-lab-tls
    namespace: ${LAB_NAMESPACE}
    files:
      - certs/ca.crt
      - certs/tls.crt
      - certs/tls.key
    options:
      disableNameSuffixHash: true
patches:
  - target:
      kind: ValidatingWebhookConfiguration
      name: mutation-capture-lab
    patch: |
      - op: replace
        path: /webhooks/0/clientConfig/caBundle
        value: ${ca_bundle}
EOF
}

wait_aggregated_api() {
    kubectl_lab -n wardle rollout status deployment/wardle-server --timeout=180s
    kubectl_lab wait apiservice/v1alpha1.wardle.example.com --for=condition=Available --timeout=180s
    local i
    for i in $(seq 1 30); do
        if kubectl_lab api-resources --api-group=wardle.example.com 2>/dev/null | grep -q flunders; then
            return 0
        fi
        sleep 2
    done
    echo "❌ the wardle APIService is Available, but discovery never listed flunders" >&2
    kubectl_lab get apiservice v1alpha1.wardle.example.com -o yaml >&2 || true
    return 1
}

import_image
write_overlay
echo "🚀 Applying the lab and the sample aggregated API server…"
kubectl_lab apply -k "${LAB_CS}"
kubectl_lab apply -k "${SAMPLE_APISERVER_DIR}"
kubectl_lab -n "${LAB_NAMESPACE}" rollout status deployment/mutation-capture-lab --timeout=180s
wait_aggregated_api
echo "✅ The lab and the sample aggregated API server are serving."
